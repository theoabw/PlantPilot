"""Package the synthetic reference plant as a 3D Gaussian splatting PLY.

The reference plant is the second scene in the scene-agnostic check: the same
`make scene` and `make objects` commands run on it, with no code change, and
the extracted boxes are scored against its ground truth. This script writes the
plant's point cloud in the same schema as the delivered capture, so the only
difference between the two scenes is the capture itself.

The plant is our own synthetic data (see docs/plantpilot-plan.md), not a
Valmet asset.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
CLOUD = ROOT / "data" / "plant" / "cloud.npz"

# The delivered capture's property order, so the second scene is the same
# schema rather than merely a compatible one.
PROPERTIES = (
    "x", "y", "z", "scale_0", "scale_1", "scale_2", "rot_1", "rot_2", "rot_3", "rot_0",
    "f_dc_0", "f_dc_1", "f_dc_2", "opacity",
) + tuple(f"f_rest_{i}" for i in range(45))

# 3DGS stores colour as 0.5 + C0 * f_dc.
SH_DC = 0.28209479177387814


def header(vertices: int) -> bytes:
    lines = [
        "ply",
        "format binary_little_endian 1.0",
        "comment Generated by scripts/make_plant_ply.py from the reference plant cloud",
        f"element vertex {vertices}",
        *[f"property float {name}" for name in PROPERTIES],
        "end_header",
        "",
    ]
    return "\n".join(lines).encode("ascii")


def to_rows(points: np.ndarray, colours: np.ndarray, *, size_m: float, alpha: float) -> np.ndarray:
    """The plant cloud as 3DGS rows, one column per delivered property."""
    columns = {name: index for index, name in enumerate(PROPERTIES)}
    rows = np.zeros((points.shape[0], len(PROPERTIES)), dtype=np.float32)
    for axis, name in enumerate(("x", "y", "z")):
        rows[:, columns[name]] = points[:, axis]
    for axis in range(3):
        rows[:, columns[f"scale_{axis}"]] = np.log(size_m)
    # An identity quaternion. The pipeline reads colour, opacity and position;
    # orientation is part of the schema and unused, so it must still be valid.
    rows[:, columns["rot_0"]] = 1.0
    rgb = np.clip(colours.astype(np.float32) / 255.0, 0.0, 1.0)
    dc = (rgb - 0.5) / SH_DC
    for axis in range(3):
        rows[:, columns[f"f_dc_{axis}"]] = dc[:, axis]
    rows[:, columns["opacity"]] = float(np.log(alpha / (1.0 - alpha)))
    return rows


def _display(path: Path) -> str:
    """A path relative to the repository when it is inside it, otherwise as given."""
    try:
        return str(Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def convert(cloud_path: Path, out: Path, *, size_m: float = 0.007, alpha: float = 0.5) -> dict:
    data = np.load(cloud_path)
    points = np.asarray(data["points"], dtype=np.float64)
    colours = np.asarray(data["colors"])
    if points.ndim != 2 or points.shape[1] != 3:
        raise SystemExit(f"{cloud_path}: expected points of shape (n, 3), got {points.shape}")
    if colours.shape[0] != points.shape[0]:
        raise SystemExit(f"{cloud_path}: {colours.shape[0]} colours for {points.shape[0]} points")
    rows = to_rows(points, colours, size_m=size_m, alpha=alpha)

    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("wb") as f:
        f.write(header(rows.shape[0]))
        f.write(rows.tobytes())
    return {
        "cloud": _display(cloud_path),
        "ply": _display(out),
        "vertices": int(rows.shape[0]),
        "properties": len(PROPERTIES),
        "bytes": out.stat().st_size,
        "gaussian_size_m": size_m,
        "alpha": alpha,
        "bbox_min": [round(float(value), 3) for value in points.min(axis=0)],
        "bbox_max": [round(float(value), 3) for value in points.max(axis=0)],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python scripts/make_plant_ply.py",
        description="Write the synthetic reference plant as a 3DGS PLY for the generality check.",
    )
    parser.add_argument("--cloud", default=CLOUD, type=Path)
    parser.add_argument("--ply", default=ROOT / "data" / "plant" / "plant.ply", type=Path)
    parser.add_argument("--gaussian-size-m", default=0.007, type=float)
    args = parser.parse_args(argv)

    if not Path(args.cloud).exists():
        raise SystemExit(f"no plant cloud at {args.cloud}; run `make plant` first")
    info = convert(Path(args.cloud), Path(args.ply), size_m=args.gaussian_size_m)
    print(json.dumps(info, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
